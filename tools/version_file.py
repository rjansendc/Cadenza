"""
Generate the Windows version resource for the built exe.

Windows reads file properties (the Details tab, and what installers and
antivirus heuristics look at) from a VERSIONINFO resource compiled into
the binary. PyInstaller takes one as a text file.

Written from core.version at build time rather than kept as a file of
its own, so the number in Cadenza.exe's properties cannot drift from
the number the About box reports.
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from core.version import __version__, APP_NAME   # noqa: E402

COMPANY     = APP_NAME
DESCRIPTION = 'GPU-accelerated editor for multi-camera concert video'
COPYRIGHT   = f'{APP_NAME}. MIT licensed.'

TEMPLATE = """# Generated by tools/version_file.py — do not edit.
# The version comes from core/version.py.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={vers},
    prodvers={vers},
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo([
      StringTable(
        '040904B0',
        [StringStruct('CompanyName',      {company!r}),
         StringStruct('FileDescription',  {description!r}),
         StringStruct('FileVersion',      {dotted!r}),
         StringStruct('InternalName',     {app!r}),
         StringStruct('OriginalFilename', {exe!r}),
         StringStruct('ProductName',      {app!r}),
         StringStruct('ProductVersion',   {dotted!r}),
         StringStruct('LegalCopyright',   {copyright!r})])
    ]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""


def version_tuple(version: str = __version__) -> tuple:
    """'1.2.0' -> (1, 2, 0, 0). Windows wants four numbers."""
    parts = [int(p) for p in version.split('.') if p.isdigit()]
    parts = (parts + [0, 0, 0, 0])[:4]
    return tuple(parts)


def version_text(version: str = __version__) -> str:
    vers = version_tuple(version)
    return TEMPLATE.format(
        vers=vers,
        dotted='.'.join(str(p) for p in vers),
        app=APP_NAME,
        exe=f'{APP_NAME}.exe',
        company=COMPANY,
        description=DESCRIPTION,
        copyright=COPYRIGHT,
    )


def write_version_file(path=None) -> str:
    """Write the resource and return its path, for the spec to use."""
    target = Path(path) if path else (
        Path(__file__).resolve().parent.parent / 'build' / 'version_info.txt')
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(version_text(), encoding='utf-8')
    return str(target)


if __name__ == '__main__':
    out = write_version_file(sys.argv[1] if len(sys.argv) > 1 else None)
    print(f'{APP_NAME} {__version__} -> {out}')
